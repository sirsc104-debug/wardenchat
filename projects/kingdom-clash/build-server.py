#!/usr/bin/env python3
"""Bundle the battle rules for the server: server/kc-battle-core.mjs.

    python3 build-server.py

The back end's trophy-battle function (BACKEND_HANDOFF.md) imports this one ES module and calls
KCServerCore.issue / setup / replay / settle. It holds the game's own js/cards.js, js/trainers.js,
js/sim.js, js/bot.js and js/progress.js with server/verify.js, inside one function, so every import
gets its own copies and nothing reaches for a page, storage or account. It runs unchanged in Deno
(Supabase Edge Functions), Node and the browser.

The rules version (a hash of the files that decide a battle) is stamped into the bundle and, by
build-artifact.py, into the game: the server refuses a trophy battle from a game with other rules
(kc_update_needed), so a battle is never checked with different rules than it was played with.
Rebuild and redeploy the bundle whenever those files change.
"""
import hashlib
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
RULE_FILES = ['js/cards.js', 'js/sim.js', 'js/bot.js', 'js/progress.js']
CORE_FILES = ['js/cards.js', 'js/trainers.js', 'js/sim.js', 'js/bot.js', 'js/progress.js', 'server/verify.js']
PLACEHOLDER = "const RULES = 'dev';"


def rules_version():
    h = hashlib.sha256()
    for f in RULE_FILES:
        h.update((HERE / f).read_bytes())
    return h.hexdigest()[:12]


def stamp(src, version):
    """Put the rules version into js/progress.js's source."""
    assert src.count(PLACEHOLDER) == 1, 'the RULES line in js/progress.js'
    return src.replace(PLACEHOLDER, f"const RULES = '{version}';")


def core_source(version):
    """The bundle's body: one function holding every file, returning KCVerify."""
    parts = []
    for f in CORE_FILES:
        src = (HERE / f).read_text(encoding='utf-8')
        if f == 'js/progress.js':
            src = stamp(src, version)
        parts.append(f'// ---- {f} ----\n{src}')
    body = '\n'.join(parts)
    return ("(() => {\n'use strict';\n"
            '// no page, storage or account here: each request runs the rules on its own copy\n'
            'const window = undefined, document = undefined, localStorage = undefined, KCBackend = undefined;\n'
            f'{body}\nreturn KCVerify;\n}})()')


def main():
    version = rules_version()
    out = HERE / 'server' / 'kc-battle-core.mjs'
    out.write_text('// Kingdom Clash: the battle rules for the server. Generated by build-server.py from\n'
                   f'// {", ".join(CORE_FILES)}: do not edit (rebuild).\n'
                   f'// Rules version {version}: the game sends the same version with each trophy battle.\n'
                   f'export const KCServerCore = {core_source(version)};\n'
                   'export default KCServerCore;\n', encoding='utf-8')
    print(f'{out.relative_to(HERE)}: rules {version}, {out.stat().st_size:,} bytes')


if __name__ == '__main__':
    main()
